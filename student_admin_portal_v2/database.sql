CREATE DATABASE IF NOT EXISTS student_portal
 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE student_portal;

CREATE TABLE IF NOT EXISTS student (
 id VARCHAR(30) NOT NULL PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 dept VARCHAR(100) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `user` (
 id VARCHAR(30) NOT NULL UNIQUE,
 phn_num VARCHAR(20) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL,
 CONSTRAINT fk_user_student FOREIGN KEY (id) REFERENCES student(id)
 ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS admins (
 admin_id INT AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE,
 phone VARCHAR(20) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL,
 role VARCHAR(30) NOT NULL DEFAULT 'Admin',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS teachers (
 teacher_id INT AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 department VARCHAR(100) NOT NULL,
 designation VARCHAR(100) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE,
 phone VARCHAR(20) NOT NULL UNIQUE,
 address VARCHAR(255) DEFAULT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;


CREATE TABLE IF NOT EXISTS class_routines (
 routine_id INT AUTO_INCREMENT PRIMARY KEY,
 department VARCHAR(100) NOT NULL, semester VARCHAR(50) NOT NULL,
 class_day VARCHAR(20) NOT NULL, course_code VARCHAR(30) NOT NULL,
 course_name VARCHAR(150) NOT NULL, teacher_name VARCHAR(100) NOT NULL,
 start_time TIME NOT NULL, end_time TIME NOT NULL, room_no VARCHAR(30) NOT NULL,
 created_by INT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_routine_lookup (department, semester, class_day)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS routine_scans (
 scan_id INT AUTO_INCREMENT PRIMARY KEY, image_path VARCHAR(255) NOT NULL,
 extracted_text MEDIUMTEXT, uploaded_by INT NULL,
 uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
