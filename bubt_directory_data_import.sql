-- Run this against the existing student_admin_portal database.
USE student_admin_portal;

CREATE TABLE IF NOT EXISTS bubt_departments (
 department_id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 department_name VARCHAR(150) NOT NULL UNIQUE,
 faculty_name VARCHAR(150) NULL,
 official_url VARCHAR(255) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS bubt_teacher_directory (
 directory_id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 teacher_name VARCHAR(150) NOT NULL,
 designation VARCHAR(120) NULL,
 department_name VARCHAR(150) NOT NULL,
 directory_role VARCHAR(80) NOT NULL DEFAULT 'Faculty',
 source_url VARCHAR(255) NULL,
 verified_on DATE NULL,
 UNIQUE KEY uq_teacher_dept_role (teacher_name, department_name, directory_role)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- Keep compatibility with an earlier import that created the tables without URL columns.
ALTER TABLE bubt_departments ADD COLUMN IF NOT EXISTS official_url VARCHAR(255) NULL;
ALTER TABLE bubt_teacher_directory ADD COLUMN IF NOT EXISTS source_url VARCHAR(255) NULL;

